CREATE TABLE IF NOT EXISTS notificationinfo (
    notificationid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid INTEGER NOT NULL REFERENCES accountinfo(accountid) ON DELETE CASCADE,
    notificationtype VARCHAR(30) NOT NULL DEFAULT 'system',
    title VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    link VARCHAR(255),
    isread SMALLINT NOT NULL DEFAULT 0 CHECK (isread IN (0, 1)),
    createdatymdt TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

