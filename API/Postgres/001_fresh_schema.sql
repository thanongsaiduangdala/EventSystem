    dateofbirth DATE,
    documentimageredpath VARCHAR(255),
    verificationstatusid INTEGER NOT NULL REFERENCES verificationstatusinfo(verificationstatusid),
    reviewedbyaccountid INTEGER REFERENCES accountinfo(accountid),
    submittedatymdt TIMESTAMP WITHOUT TIME ZONE,
    reviewedatymdt TIMESTAMP WITHOUT TIME ZONE
);

-- Personalization/notifications (from create_missing_tables.sql and invite flow).
