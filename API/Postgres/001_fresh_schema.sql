CREATE TABLE IF NOT EXISTS eventviewinfo (
    viewid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid INTEGER NOT NULL REFERENCES accountinfo(accountid) ON DELETE CASCADE,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    viewedatymdt TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
