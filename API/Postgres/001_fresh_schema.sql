-- Explicit identity values in seed INSERTs do not advance PostgreSQL sequences.
-- GREATEST keeps a sequence from going backwards if the script is re-run
-- after a high-ID lookup entry was created and later deleted.
SELECT setval(pg_get_serial_sequence('accountstatusinfo', 'statusid'),
    GREATEST((SELECT max(statusid) FROM accountstatusinfo),
             (SELECT last_value FROM accountstatusinfo_statusid_seq)), true);
