-- Fresh PostgreSQL / Supabase schema for the API reservation system.
-- Run in an empty schema (normally public). Safe to re-run for tables/indexes and
-- reference seeds; this is NOT an upgrade script for a partially migrated MySQL DB.
-- No accounts, orders, events, personal data, sponsors, or user categories are seeded.
-- Identifiers deliberately use unquoted lowercase: PostgreSQL folds API's unquoted
-- CamelCase SQL identifiers to lowercase. Integer flags are SMALLINT, not BOOLEAN,
-- because the API writes 0/1 and compares flags to numeric 1.
-- MySQL DATETIME is represented by TIMESTAMP WITHOUT TIME ZONE; the application
-- must use a consistent timezone (preferably UTC) when writing timestamps.

BEGIN;

-- Fixed references and role/permission catalog.
CREATE TABLE IF NOT EXISTS accountstatusinfo (
    statusid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statustype VARCHAR(45) NOT NULL
);

CREATE TABLE IF NOT EXISTS eventstatusinfo (
    eventstatusid INTEGER PRIMARY KEY,
    statusname VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS organizerstatusinfo (
    organizerstatusid INTEGER PRIMARY KEY,
    statusname VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS eventquestiontype (
    eventquestiontypeid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventquestiontype VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS eventrole (
    eventroleid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rolename VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS teamrole (
    teamroleid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teamrolename VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS memberstatusinfo (
    memberstatusid INTEGER PRIMARY KEY,
    statusname VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS paymenttypeinfo (
    paymenttypeid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paymenttypename VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS verificationstatusinfo (
    verificationstatusid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statusname VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS verificationtypeinfo (
    verificationtypeid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtype VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS permissioninfo (
    permissionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permissionname VARCHAR(100) NOT NULL UNIQUE,
    permissiondescription VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rolepermissioninfo (
    rolepermissionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statusid INTEGER NOT NULL REFERENCES accountstatusinfo(statusid) ON DELETE CASCADE,
    permissionid INTEGER NOT NULL REFERENCES permissioninfo(permissionid) ON DELETE CASCADE,
    CONSTRAINT uq_status_permission UNIQUE (statusid, permissionid)
);

-- Accounts, organizations, categories, events.
CREATE TABLE IF NOT EXISTS accountinfo (
    accountid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(50) NOT NULL,
    lastname VARCHAR(50) NOT NULL,
    phonenum VARCHAR(20) NOT NULL,
    profileimagepath VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    statusid INTEGER NOT NULL REFERENCES accountstatusinfo(statusid),
    passwordenc VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS categoryinfo (
    categoryid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryname VARCHAR(50) NOT NULL,
    categoryiconpath VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS eventorganizerinfo (
    eventorganizerid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventorganizername VARCHAR(255) NOT NULL,
    eventorganizerlogopath VARCHAR(255) NOT NULL,
    createdbyaccountid INTEGER NOT NULL REFERENCES accountinfo(accountid),
    -- The API inserts NULL for optional descriptions.
    eventorganizerdiscription TEXT,
    -- Application flow: 1 pending, 2 approved, 3 denied.
    organizerstatusid INTEGER NOT NULL DEFAULT 1 REFERENCES organizerstatusinfo(organizerstatusid)
);

CREATE TABLE IF NOT EXISTS eventinfo (
    eventid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventname VARCHAR(100) NOT NULL,
    eventstartingymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    eventendingymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    eventaddress VARCHAR(255) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    eventdescription TEXT NOT NULL,
    eventorganizerid INTEGER NOT NULL REFERENCES eventorganizerinfo(eventorganizerid),
    oneperperson SMALLINT NOT NULL DEFAULT 0 CHECK (oneperperson IN (0, 1)),
    -- Original dump defaulted to Approved; the API explicitly sets Pending
    -- on non-admin creations. Keep that default for legacy INSERT callers.
    eventstatusid INTEGER NOT NULL DEFAULT 2 REFERENCES eventstatusinfo(eventstatusid),
    eventvisible SMALLINT NOT NULL DEFAULT 1 CHECK (eventvisible IN (0, 1)),
    -- Used by the current team dashboard, though absent in the MySQL dump.
    scanenabled SMALLINT NOT NULL DEFAULT 0 CHECK (scanenabled IN (0, 1))
);

CREATE TABLE IF NOT EXISTS organizermember (
    memberid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid INTEGER NOT NULL REFERENCES accountinfo(accountid),
    eventorganizerid INTEGER NOT NULL REFERENCES eventorganizerinfo(eventorganizerid) ON DELETE CASCADE,
    teamroleid INTEGER NOT NULL REFERENCES teamrole(teamroleid),
    -- Old members were backfilled Active in the invite migration.
    memberstatusid INTEGER NOT NULL DEFAULT 2 REFERENCES memberstatusinfo(memberstatusid)
);

-- Equivalent to the MySQL generated ActiveMembershipKey unique index: there
-- may be many removed (status 4) rows, but only one live invitation/membership.
CREATE UNIQUE INDEX IF NOT EXISTS uq_organizer_active_member
    ON organizermember (accountid, eventorganizerid) WHERE memberstatusid <> 4;

CREATE TABLE IF NOT EXISTS eventstaff (
    -- Preserve the typo in the MySQL/API column name, not "assignmentid".
    assigmentid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    memberid INTEGER NOT NULL REFERENCES organizermember(memberid),
    eventroleid INTEGER NOT NULL REFERENCES eventrole(eventroleid),
    assignedatymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    canscan SMALLINT NOT NULL DEFAULT 0 CHECK (canscan IN (0, 1)),
    CONSTRAINT uq_event_staff_member UNIQUE (eventid, memberid)
);

CREATE TABLE IF NOT EXISTS eventcategoryinfo (
    eventcategoryid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    categoryid INTEGER NOT NULL REFERENCES categoryinfo(categoryid)
);

CREATE TABLE IF NOT EXISTS eventimageinfo (
    imageid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    imagename VARCHAR(50) NOT NULL,
    imagepath VARCHAR(255) NOT NULL,
    isthumbnail SMALLINT NOT NULL DEFAULT 0 CHECK (isthumbnail IN (0, 1))
);

CREATE TABLE IF NOT EXISTS eventquestioninfo (
    eventquestionid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    eventquestion VARCHAR(255) NOT NULL,
    eventquestiontypeid INTEGER NOT NULL REFERENCES eventquestiontype(eventquestiontypeid),
    -- The API binds a Python bool directly for this field (unlike its other 0/1 flags).
    isrequire BOOLEAN NOT NULL,
    sortorder INTEGER NOT NULL,
    -- API json.dumps/json.loads expects a string rather than a decoded JSONB.
    options TEXT
);

CREATE TABLE IF NOT EXISTS sponserinfo (
    sponserid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsername VARCHAR(50) NOT NULL,
    sponserlogopath VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS eventsponserinfo (
    eventsponserid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    sponserid INTEGER NOT NULL REFERENCES sponserinfo(sponserid)
);

CREATE TABLE IF NOT EXISTS tickettype (
    tickettypeid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    typename VARCHAR(45) NOT NULL,
    priceinkip INTEGER NOT NULL,
    capacity INTEGER NOT NULL,
    salestartymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    saleendymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS ordersinfo (
    orderid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid INTEGER NOT NULL REFERENCES accountinfo(accountid),
    paymenttypeid INTEGER REFERENCES paymenttypeinfo(paymenttypeid),
    -- The API can send NULL explicitly, even for free tickets.
    paymentdateymdt TIMESTAMP WITHOUT TIME ZONE,
    proveofpayment VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS ticketattendence (
    attendeeid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tickettypeid INTEGER NOT NULL REFERENCES tickettype(tickettypeid),
    orderid INTEGER NOT NULL REFERENCES ordersinfo(orderid) ON DELETE CASCADE,
    firstname VARCHAR(50) NOT NULL,
    lastname VARCHAR(50) NOT NULL,
    phonenum VARCHAR(20) NOT NULL,
    email VARCHAR(255) NOT NULL,
    nationalid VARCHAR(50),
    isvalid SMALLINT NOT NULL DEFAULT 1 CHECK (isvalid IN (0, 1))
);

CREATE TABLE IF NOT EXISTS attendeeresponse (
    responseid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventquestionid INTEGER NOT NULL REFERENCES eventquestioninfo(eventquestionid) ON DELETE CASCADE,
    attendeeid INTEGER NOT NULL REFERENCES ticketattendence(attendeeid) ON DELETE CASCADE,
    attendeeanswer VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS ticketcheckin (
    checkinid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendeeid INTEGER NOT NULL REFERENCES ticketattendence(attendeeid) ON DELETE CASCADE,
    eventid INTEGER NOT NULL REFERENCES eventinfo(eventid) ON DELETE CASCADE,
    checkedinbymemberid INTEGER NOT NULL REFERENCES organizermember(memberid),
    checkedinatymdt TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_attendee_event UNIQUE (attendeeid, eventid)
);

CREATE TABLE IF NOT EXISTS identityverification (
    verificationid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid INTEGER NOT NULL REFERENCES accountinfo(accountid),
    verificationtypeid INTEGER NOT NULL REFERENCES verificationtypeinfo(verificationtypeid),
    idnumberencrypted VARCHAR(255) NOT NULL,
    fullnameonid VARCHAR(255) NOT NULL,
